      <h3>2.3. Inhalte</h3>
      <h4>2.3.1. Fachwissenschaftliche Sachanalyse</h4>

      <p>Die additive Fertigung, umgangssprachlich als 3D-Druck bezeichnet, umfasst Fertigungsverfahren, bei denen
        dreidimensionale Objekte durch schichtweisen Aufbau aus digitalen 3D-Daten hergestellt werden. Im Gegensatz zu
        subtraktiven Verfahren (z. B. Fräsen) wird Material gezielt hinzugefügt, wodurch eine hohe Materialeffizienz und
        die Realisierung komplexer Geometrien möglich sind.</p>

      <p><strong>FDM – Fused Deposition Modeling (Schmelzschichtung):</strong> Bei der Schmelzschichtung wird im
        Extruder des Druckkopfs ein Kunststoffdraht (Thermoplast) geschmolzen und durch die Düse gepresst. Der Druckkopf
        verfährt in der x- und y-Richtung, sodass eine Schicht des Bauteils entsteht. Anschließend fahren Druckkopf und
        Bauplatte um eine Schichtstärke auseinander, und die nächste Schicht wird aufgebaut. Um Hohlräume erzeugen zu
        können, kann ein zweiter Extruder mit Stützmaterial eingesetzt werden. FDM-Drucker kommen wegen ihrer
        vergleichsweise geringen Kosten auch im Hobbybereich zum Einsatz. Typische Merkmale: mittlere Detailgenauigkeit,
        sichtbare Schichten, meist erforderliche Stützstrukturen, vergleichsweise geringe Kosten.</p>

      <p><strong>SLA – Stereolithografie (Lichthärtungsverfahren):</strong> Die Stereolithografie ist das älteste
        3D-Druckverfahren. Das 3D-Objekt entsteht aus einem zähflüssigen lichtempfindlichen Polymer (Photopolymer), das
        an den gewünschten Stellen Schicht für Schicht mit UV-Licht ausgehärtet wird. Das Verfahren zeichnet sich durch
        sehr hohe Detailgenauigkeit und sehr glatte Oberflächen aus. Hohle Objekte sind nur möglich, wenn Öffnungen zum
        Herauswaschen des ungebundenen Polymers vorgesehen sind. Typische Anwendung: Präsentationsmodelle und
        detailreiche Modelle.</p>

      <p><strong>SLS – Selektives Lasersintern (Laserverschmelzung von Pulver):</strong> Beim selektiven Lasersintern
        wird eine dünne Pulverschicht aus Polymer oder Metall auf eine Trägerplatte aufgebracht und an den definierten
        Stellen mittels Laserstrahl verschmolzen. Danach wird die Trägerplatte abgesenkt, die nächste Pulverschicht
        aufgebracht und erneut verschmolzen. Das umgebende ungebundene Pulver übernimmt die Stützfunktion, sodass keine
        separaten Stützstrukturen erforderlich sind. SLS bietet hohe Detailgenauigkeit, leicht raue Oberflächen und ist
        besonders für industrielle Funktionsbauteile geeignet, allerdings mit vergleichsweise hohen Kosten verbunden.
      </p>

      <p class="literatur"><strong>Literatur:</strong><br />
        Bühler, P. / Schlaich, P. / Sinner, D. / Stauss, A. / Stauss, T. (2019): <em>Produktdesign. Konzeption – Entwurf – Technologie.</em> Springer Vieweg, Berlin. ISBN 978-3-662-55510-1.</p>

      <h4>2.3.2. Fachdidaktische Analyse</h4>

      <p>Der Unterrichtsgegenstand ist im Bildungsplan des Beruflichen Gymnasiums für das Fach Gestaltungs- und
        Medientechnik curricular verbindlich verankert. BPE 13.3 (Modellbau und Prototyp) weist die generative
        Fertigung von Modellen als inhaltlichen Schwerpunkt aus; BPE 14.2 (Fertigung von Produkten) nennt generative
        Fertigungsverfahren explizit als zu behandelnde
        Inhalte. Die Stunde greift damit einen doppelt verankerten Inhaltsbereich auf, dem zugleich hohe
        berufsfeldbezogene Relevanz zukommt: Additive Fertigungsverfahren sind in der Prototypenentwicklung, im
        Produktdesign und in der industriellen Fertigung etabliert und zählen zu den prägenden Technologien der
        modernen Produktion.</p>

      <p>Die Entscheidung für die Gruppenpuzzle-Methode (Jigsaw) folgt aus der Struktur des Lerngegenstandes: Die drei
        Verfahren FDM, SLA und SLS sind thematisch eng verwandt, inhaltlich jedoch eigenständig und damit für eine
        arbeitsteilige Erarbeitung geeignet. Die Methode überträgt den SuS Verantwortung für einen Teilbereich und
        erzeugt durch die anschließende Verpflichtung, das Erarbeitete in der Stammgruppe zu erklären, eine hohe
        intrinsische Motivation zur wirklichen Durchdringung des Lernstoffs. Dieses Prinzip der reziproken Vermittlung
        generiert nachhaltigeres Wissen als eine rezeptive Aufnahme im Frontalvortrag, da das Verstehen zur
        Voraussetzung für das Erklären wird.</p>

      <p>Den Einstieg bildet ein gezielt spielerischer Impuls: Die SuS lösen auf ihren Endgeräten ein interaktives
        Puzzle-Game, das einen 3D-gedruckten Sneaker enthüllt und so unmittelbar Aufmerksamkeit erzeugt, ohne das
        Stundenthema vorwegzunehmen. Der Übergang von diesem Einstieg in die Gruppenphase erfolgt bewusst zügig, da
        die kooperative Erarbeitung den inhaltlichen Kern der Stunde bildet und den größten Zeitanteil beansprucht.</p>

      <p>Der Einsatz der webbasierten Lernumgebung erfüllt in diesem Arrangement eine zentrale Kontrollfunktion: Da
        M. Heckel in der Expertenphase nicht alle Gruppen gleichzeitig begleiten kann, stellt die Anwendung durch
        strukturierte Aufgabenformate und automatisiertes Feedback sicher, dass die SuS inhaltlich korrektes Wissen
        weitergeben. Fehlerhaftes oder unvollständiges Verständnis wird so vor der Stammgruppenphase identifiziert und
        korrigiert – eine Qualitätssicherung, die strukturell nicht durch die Lehrkraft allein leistbar wäre.</p>

      <p>In der Stammgruppenphase präsentieren die SuS ihr jeweiliges Verfahren den Mitschülerinnen und Mitschülern.
        Diese Phase gewährleistet eine hohe Aktivierung aller SuS, da – anders als im lehrerzentrierten Vortrag – jede
        Person sowohl als Erklärender als auch als Lernender agiert. Die abschließenden Transferfragen konsolidieren
        das Wissen, indem sie einen kriteriengeleiteten Verfahrensvergleich einfordern. Die Möglichkeit, die
        Arbeitsergebnisse als PDF herunterzuladen, dokumentiert den Lernstand und stellt die Ergebnisse
        für eine spätere Verwendung zur Verfügung.</p>
