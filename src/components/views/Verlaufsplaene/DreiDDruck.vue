      <p>Im Anschluss werden die Stammgruppen gebildet und die Expertenrollen vergeben – je eine pro Verfahren:
        Schmelzschichtung (FDM), Stereolithografie (SLA) und Selektives Lasersintern (SLS). Die Rollenverteilung
        erfolgt über die Lernumgebung: Die SuS wählen ihre Rolle durch Antippen aus und machen damit ihre Zugehörigkeit
        sichtbar. Danach finden sich alle SuS mit gleicher Expertenrolle in ihrer Expertengruppe zusammen.</p>

      <h4>Phase 3: Expertenphase – Erarbeitung mit der Webapplikation</h4>
      <p>Die Expertenphase stellt die inhaltliche Kernphase der Stunde dar. Jede Expertengruppe erarbeitet ihr Verfahren
        mithilfe der webbasierten Lernumgebung, die strukturiert durch drei Aufgabenformate führt: einen einführenden
        Fachtext, eine Drag-and-Drop-Aufgabe zur Reihenfolge der Prozessschritte sowie eine Multiple-Choice-Aufgabe zur
        Zuordnung wesentlicher Merkmale (Ausgangsmaterial, Detailgenauigkeit, Kosten, typische Anwendung). Die SuS
        können ihre Lösungen jederzeit eigenständig überprüfen. Sobald alle Aufgaben korrekt gelöst sind, erhalten sie
        einen verfahrensspezifischen Expertencode, mit dem ihre Ergebnisse auf der Ergebnisseite der Lernumgebung
        angezeigt werden. M. Heckel begleitet die Gruppen beratend und unterstützt bei Verständnisschwierigkeiten.</p>

      <h4>Phase 4: Stammgruppenphase – Wissenstransfer</h4>
      <p>Nach der Expertenphase kehren die SuS in ihre Stammgruppen zurück. Jedes Mitglied präsentiert das erarbeitete
        Verfahren und erläutert den anderen Mitgliedern dessen Funktionsprinzip, wesentliche Merkmale und typische
        Anwendungsbereiche. Das Erklären stellt eine kognitiv anspruchsvollere Leistung dar als das bloße Rezipieren:
        Es erfordert, das eigene Verständnis zu verdichten, zu strukturieren und adressatengerecht zu formulieren.
        Rückfragen innerhalb der Stammgruppe sind ausdrücklich erwünscht.</p>

      <h4>Phase 5: Transfer und Sicherung</h4>
      <p>Den Abschluss bildet eine Transferphase: Die SuS vergleichen die drei Verfahren
        kriteriengeleitet und wählen für konkrete Anwendungsfälle das jeweils geeignete Verfahren aus. Diese Aufgaben
        fordern eine begründete Entscheidung, die über die bloße Reproduktion
        von Merkmalen hinausgeht. Die Arbeitsergebnisse können abschließend als PDF heruntergeladen werden und stehen
        den SuS als persönliches Lernprodukt zur Verfügung.</p>

      <p>Insgesamt entsteht ein
        Lernarrangement, das individuelle Erarbeitung (Expertenphase), kooperative Wissensvermittlung (Stammgruppe)
        und anwendungsbezogenes Denken (Transfer) strukturell miteinander verzahnt.</p>
