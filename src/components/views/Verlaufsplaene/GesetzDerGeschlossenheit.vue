      <h3>2.4. Gestaltung des Lehr-/Lernarrangements</h3>

      <p>Die Unterrichtsstunde ist im Sinne eines handlungsorientierten und praxisnahen Unterrichts konzipiert, wie er
        für das Fach Berufspraktische Kompetenz charakteristisch ist. Ziel ist es, die Schülerinnen und Schüler
        schrittweise an reale Arbeitsprozesse der Mediengestaltung heranzuführen. Die gewählte Unterrichtskonzeption
        verbindet lehrerzentrierte und schülerzentrierte Phasen und orientiert sich an einem angeleiteten,
        exemplarischen Lernen. Aufgrund der geringen Vorkenntnisse der Lerngruppe wird ein überwiegend deduktives
        Vorgehen gewählt: Zunächst wird das Gestaltungsprinzip eingeführt und erläutert, bevor es in einer klar
        strukturierten Aufgabe angewendet wird.</p>

      <p>Der Einstieg erfolgt lehrerzentriert durch einen visuellen Impuls in Form einer kurzen Animation, die ein
        Wahrnehmungsphänomen zeigt. Ziel dieser Phase ist es, die Aufmerksamkeit der Schülerinnen und Schüler zu
        aktivieren und einen ersten Zugang zum Thema Wahrnehmung zu schaffen. Durch gezielte Fragestellungen werden die
        Lernenden in ein Unterrichtsgespräch eingebunden, sodass bereits hier eine erste kognitive Aktivierung
        stattfindet.</p>

      <p>In der anschließenden Erarbeitungsphase I führt die Lehrkraft das Gestaltgesetz der Geschlossenheit anhand von
        Beispielen ein. Diese Phase ist ebenfalls stärker lehrerzentriert, da ein gemeinsames inhaltliches Fundament
        geschaffen werden muss. Die Schülerinnen und Schüler entwickeln dabei ein grundlegendes Verständnis für das
        Gesetz der Geschlossenheit, das im weiteren Verlauf der Stunde angewendet wird.</p>

      <p>Darauf aufbauend erfolgt die Erarbeitungsphase II, in der der Arbeitsauftrag vorgestellt und erläutert wird.
        Die Aufgabenstellung ist bewusst klar strukturiert, und die Wissenssicherung erfolgt angeleitet über
        Multiple-Choice-Fragen, um der Lerngruppe Sicherheit zu geben und Überforderung zu vermeiden.</p>

      <p>Die anschließende Durchführungsphase ist schülerzentriert angelegt und erfolgt überwiegend in Einzelarbeit.
        Diese Sozialform ist sinnvoll, da jede Schülerin und jeder Schüler eine eigene gestalterische Lösung entwickeln
        soll. Die Lehrkraft übernimmt hier eine beratende und unterstützende Rolle, gibt individuelle Hilfestellungen
        und reagiert flexibel auf unterschiedliche Lernstände. Im Sinne der Binnendifferenzierung werden schnell
        arbeitenden Schülerinnen und Schülern zusätzliche Aufgaben angeboten, während andere durch gezielte Impulse
        unterstützt werden. Der Einsatz von einfachen analogen Medien wie Papier, Schere ermöglicht einen
        niedrigschwelligen Zugang zur Gestaltung und fördert das experimentelle Arbeiten.</p>

