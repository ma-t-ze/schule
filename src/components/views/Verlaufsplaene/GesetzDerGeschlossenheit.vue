      <h3>2.3. Inhalte</h3>
      <h4>2.3.1. Fachwissenschaftliche Sachanalyse</h4>

      <p>Die Grundlagen der visuellen Wahrnehmung in der Gestaltung basieren auf der Gestaltpsychologie, die sich mit
        der Analyse menschlicher Wahrnehmungsprozesse beschäftigt. Sie geht davon aus, dass Wahrnehmung nicht aus
        isolierten Einzelreizen besteht, sondern durch das Erkennen und Ordnen von Formen erfolgt. Nur so kann „die
        unbestimmte Komplexität der Sinneswahrnehmungen aufgelöst und bewertet werden".</p>

      <p>Die Gestaltgesetze beschreiben, wie visuelle Elemente zu sinnvollen Einheiten organisiert werden und „wie und
        warum Formen als eine bestimmte Gestalt erlebt werden". Sie bilden damit eine zentrale Grundlage für
        gestalterische Entscheidungen, da sie erklären, wie visuelle Reize beim Betrachter wirken und interpretiert
        werden.</p>

      <p>Ein wesentliches Gestaltgesetz ist das Gesetz der Geschlossenheit. Dieses besagt, dass „geschlossene Flächen
        als Einheit erkannt" werden und das Gehirn dazu neigt, unvollständige Formen zu ergänzen, um sinnvolle
        Zusammenhänge herzustellen. Wahrnehmung ist somit ein aktiver Prozess, bei dem fehlende Informationen ergänzt
        und zu bekannten, meist einfachen Formen organisiert werden.</p>

      <p>In der Gestaltung wird dieses Prinzip gezielt eingesetzt, insbesondere im Logodesign. Durch bewusste Reduktion
        und das Weglassen von Elementen entstehen prägnante Zeichen, die vom Betrachter ergänzt werden und dadurch eine
        hohe Einprägsamkeit erhalten. Bekannte Logos wie das IBM-Logo nutzen dieses Prinzip, indem Flächen bewusst offen
        bleiben. So entsteht ein hoher Wiedererkennungswert, der für erfolgreiche visuelle Kommunikation zentral ist.
      </p>

      <p class="literatur"><strong>Literatur:</strong><br />
        Rohles, B.; Burkhardt, R.; Wolf, J.; Linnemann, C.; Rohrlich, M. (2019): Mediengestaltung – Der
        Ausbildungsbegleiter. Bonn: Rheinwerk Verlag.</p>

      <h4>2.3.2. Fachdidaktische Analyse</h4>

      <p>Die Auswahl des Unterrichtsinhalts orientiert sich am Bildungsplan der Berufsfachschule für Druck- und
        Medientechnik, insbesondere an den Lernfeldern „Medienprodukte gestalten und herstellen". Der Schwerpunkt liegt
        auf der Entwicklung grundlegender Gestaltungskompetenzen im Bereich Corporate Identity und Logodesign. Die
        Entscheidung für das Gestaltgesetz der Geschlossenheit als zentrales Thema ist didaktisch begründet, da es ein
        klar strukturiertes und gut nachvollziehbares Prinzip darstellt, das auch ohne umfangreiche Vorkenntnisse
        angewendet werden kann.</p>

      <p>Die Stoffstruktur folgt einem projektorientierten Aufbau. Ausgangspunkt ist die Auswahl einer Schrift mit einem
        bestimmten Charakter, auf deren Grundlage ein Moodboard erstellt und anschließend ein eigenes Produkt entwickelt
        wird. Darauf aufbauend werden weitere Gestaltungselemente wie das Logo erarbeitet. Die aktuelle Stunde führt ein
        konkretes Gestaltungsprinzip ein, das bei der Gestaltung des Logos zur Anwendung kommt.</p>

      <p>Im Sinne der didaktischen Reduktion wird bewusst auf eine umfassende Einführung in alle Gestaltgesetze
        verzichtet. Stattdessen wird mit dem Gesetz der Geschlossenheit ein einzelnes, besonders anschauliches Prinzip
        ausgewählt. Dieses ermöglicht es den Schülerinnen und Schülern, Gestaltung unmittelbar praktisch zu erfahren und
        erste Erfolgserlebnisse zu erzielen. Gleichzeitig wird die Komplexität der Aufgabe reduziert, indem der
        Gestaltungsprozess stark angeleitet erfolgt. Dies ist notwendig, da die Lerngruppe über kaum Vorkenntnisse im
        Bereich Logogestaltung verfügt und eine offene Aufgabenstellung zu Überforderung führen würde.</p>

      <p>Das didaktische Potenzial der Stunde liegt insbesondere in der Verbindung von Wahrnehmung und Gestaltung. Die
        Schülerinnen und Schüler erkennen, dass visuelle Gestaltung gezielt eingesetzt werden kann, um bestimmte
        Wirkungen beim Betrachter zu erzeugen. Durch die praktische Anwendung des Gestaltgesetzes der Geschlossenheit
        erfahren sie, wie durch bewusste Formgestaltung ein prägnantes und einprägsames Logo entsteht. Gleichzeitig wird
        die Fähigkeit gefördert, Gestaltung zu reflektieren und zu beschreiben.</p>

      <p>Das Thema besitzt einen hohen Bezug zur Erfahrungswelt der Schülerinnen und Schüler. Logos sind ein fester
        Bestandteil ihres Alltags und begegnen ihnen ständig in Medien, Werbung und digitalen Anwendungen. Gleichzeitig
        stellt die Auseinandersetzung mit Corporate Identity einen direkten Bezug zur beruflichen Praxis im Bereich
        Druck- und Medientechnik her. Die Schülerinnen und Schüler arbeiten an einer Aufgabe, die sich an realen
        Gestaltungsprozessen orientiert und somit berufsvorbereitenden Charakter hat.</p>

      <p>Darüber hinaus bestehen Verknüpfungen zu weiteren Unterrichtsinhalten und Lernfeldern, insbesondere zur
        Typografie.</p>

      <p>Als Alternative wäre eine freiere Herangehensweise an die Logoentwicklung denkbar gewesen. Diese wurde jedoch
        bewusst verworfen, da sie dem Leistungsstand der Lerngruppe nicht entspricht und zu Überforderung führen könnte.
        Ebenso wäre eine theoretisch umfassendere Behandlung mehrerer Gestaltgesetze möglich gewesen, wurde jedoch
        zugunsten einer klaren Fokussierung reduziert, um nachhaltiges Lernen und praktische Anwendung zu ermöglichen.
      </p>
