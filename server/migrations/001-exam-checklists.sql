CREATE TABLE IF NOT EXISTS school_exam_checklists (
    exam_key VARCHAR(60) NOT NULL PRIMARY KEY,
    announced BOOLEAN NOT NULL DEFAULT FALSE,
    materials BOOLEAN NOT NULL DEFAULT FALSE,
    teams_announced BOOLEAN NOT NULL DEFAULT FALSE,
    handed_out BOOLEAN NOT NULL DEFAULT FALSE,
    accommodation BOOLEAN NOT NULL DEFAULT FALSE,
    makeup_names TEXT NOT NULL,
    revision INT UNSIGNED NOT NULL DEFAULT 1,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
